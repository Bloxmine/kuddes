/**
 * The classic short codes Hyves turned into smileys, and codes used before
 * Kuddes had the Hyves set, mapped to a smiley name.
 */
export const SMILEY_ALIASES: Record<string, string> = {
  ':-)': 'lach',
  ':)': 'lach',
  ':-d': 'groot',
  ':d': 'groot',
  ';-)': 'knipoog',
  ';)': 'knipoog',
  ':-(': 'verdrietig',
  ':(': 'verdrietig',
  ':-p': 'tong2',
  ':p': 'tong2',
  ':$': 'schamen',
  ':-s': 'indewar',
  ':s': 'indewar',
  '(l)': 'love_heart',
  '(h)': 'bril',
  ':ping:': 'blackberry_pingen',
}

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const aliasCodes = Object.keys(SMILEY_ALIASES)
  .sort((a, b) => b.length - a.length)
  .map(escape)

/**
 * Matches :name: for any smiley and the short codes. Named codes come first,
 * so ":sleeping:" isn't read as ":s" followed by "leeping:".
 */
export const SMILEY_PATTERN = new RegExp(`(:[A-Za-z0-9_]+:|${aliasCodes.join('|')})`, 'g')

/** The smiley name for a code, or null when it isn't one. */
export function smileyName(code: string): string | null {
  const lower = code.toLowerCase()
  if (SMILEY_ALIASES[lower]) return SMILEY_ALIASES[lower]
  if (code.startsWith(':') && code.endsWith(':')) {
    const name = code.slice(1, -1)
    if (SMILEYS[name]) return name
    // Names are lowercase except "XD"; accept any capitalisation
    const match = Object.keys(SMILEYS).find((n) => n.toLowerCase() === name.toLowerCase())
    return match ?? null
  }
  return null
}
